#!/usr/bin/env bash
# Smoothness of on-screen movement vs snapshot rate, without and with client
# interpolation (#15).
#
# Usage: bench/smooth.sh <label>      (needs build/server and build/client)
#
# For each snapshot rate in RATES and each interpolation mode (off, on),
# TRIALS times: start the server with --snapshot-hz <rate>, two clients that
# move on their own (FUSE_AUTO_MOVE=1: right, down, left, up for 1 s each at
# 180 px/s), and one observer client run with
#   --interp <mode> --smooth-stats DURATION
# which measures every frame how far each moving player moved on screen and
# compares that with its real speed (client/interp.h, interp_stats_print):
#   speed_rms_err  RMS of (on-screen speed - real speed), px/s; 0 = perfectly
#                  even movement
#   stall_pct      % of frames in which a moving player did not move on screen
#   max_step_px    largest on-screen jump in one frame
# The observer's window is open, so frames are paced by the display.
#
# Settings (environment): RATES ["60 30 20 10"], TRIALS [3], DURATION [12] s.
# Uses the security policy's domain 0; refuses to run beside an existing server.
# Results: bench/results/<label>/{setup.txt, raw/smooth.txt, report.txt}

set -euo pipefail
cd "$(dirname "$0")/.."

LABEL=${1:?usage: bench/smooth.sh <label>}
RATES=${RATES:-60 30 20 10}
TRIALS=${TRIALS:-3}
DURATION=${DURATION:-12}
OUT=bench/results/$LABEL
mkdir -p "$OUT/raw"
source bench/security_env.sh
dds_check_clients 3
for str_server in server baseline_server; do
    if pgrep -x "$str_server" > /dev/null; then
        echo "Stop the existing $str_server before running the smoothness comparison" >&2
        exit 1
    fi
done

for bin in build/server build/client; do
    [ -x "$bin" ] || { echo "Missing $bin (make)" >&2; exit 1; }
done

source bench/setup_info.sh
write_setup "$LABEL" build/server build/client > "$OUT/setup.txt"

int_server_pid=0
arr_mover_pids=()
cleanup() {
    [ "$int_server_pid" -eq 0 ] || kill "$int_server_pid" "${arr_mover_pids[@]}" 2> /dev/null || true
    wait 2> /dev/null || true
}
trap cleanup EXIT

RAW=$OUT/raw/smooth.txt
: > "$RAW"
for rate in $RATES; do
    for trial in $(seq "$TRIALS"); do
        for mode in off on; do
            dds_run server build/server --snapshot-hz "$rate" > /dev/null 2>&1 &
            int_server_pid=$!
            arr_mover_pids=()
            for int_client in 1 2; do
                FUSE_AUTO_MOVE=1 dds_run "client-$int_client" build/client > /dev/null 2>&1 &
                arr_mover_pids+=($!)
            done
            sleep 1
            str_line=$(dds_run client-3 build/client --interp "$mode" --smooth-stats "$DURATION" 2> /dev/null | grep '^interp=' || echo "interp=$mode failed")
            echo "rate=$rate trial=$trial $str_line" | tee -a "$RAW"
            cleanup
            int_server_pid=0
            sleep 1
        done
    done
done

# report.txt: mean of the trials per rate and mode
{
    echo "Smoothness vs snapshot rate (#15), label $LABEL"
    echo "Generated by bench/smooth.sh on $(date -Iseconds); per-trial lines in raw/smooth.txt"
    echo "2 moving clients (180 px/s), 1 observer client measuring for ${DURATION} s, $TRIALS trials each"
    echo
    printf '%-6s %-7s %8s %15s %10s %12s\n' rate interp fps speed_rms_err stall_pct max_step_px
    awk '{
        for (i = 1; i <= NF; i++) { split($i, kv, "="); v[kv[1]] = kv[2] }
        k = v["rate"] " " v["interp"]
        if (!(k in n)) order[++m] = k
        n[k]++; fps[k] += v["fps"]; err[k] += v["speed_rms_err"]; st[k] += v["stall_pct"]
        if (v["max_step_px"] > mx[k]) mx[k] = v["max_step_px"]
    } END {
        for (j = 1; j <= m; j++) { k = order[j]; split(k, a, " ")
            printf "%-6s %-7s %8.1f %15.1f %10.1f %12.1f\n", a[1], a[2], fps[k]/n[k], err[k]/n[k], st[k]/n[k], mx[k] }
    }' "$RAW"
    echo
    echo "speed_rms_err: px/s, mean of trials; stall_pct: mean of trials; max_step_px: max over trials"
} > "$OUT/report.txt"
cat "$OUT/report.txt"
